package geoserver

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// WriteConnectionsFile writes geoserver-connections.properties for Java GeoServerAuth.
// Mirrors PHP jrs_write_geoserver_connections_file.
func WriteConnectionsFile(path string, rows []Connection) error {
	path = strings.TrimSpace(path)
	if path == "" {
		return fmt.Errorf("geoserver connections path is empty")
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}

	var b strings.Builder
	b.WriteString("# Generated by AcuGIS Report Server — do not edit by hand\n")
	b.WriteString("# Java: com.acugis.map.GeoServerAuth (system property acugis.geoserver.connections.file)\n")
	b.WriteString("# Keys are stable connection names matching Designer Connection Manager / JRXML connectionName\n")
	b.WriteString("\n")
	for _, row := range rows {
		name := strings.TrimSpace(row.Name)
		if name == "" {
			continue
		}
		b.WriteString("# " + name + "\n")
		b.WriteString(name + ".url=" + propEscape(strings.TrimRight(strings.TrimSpace(row.URL), "/")) + "\n")
		b.WriteString(name + ".username=" + propEscape(strings.TrimSpace(row.Username)) + "\n")
		b.WriteString(name + ".password=" + propEscape(row.Password) + "\n")
		b.WriteString("\n")
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func propEscape(value string) string {
	replacer := strings.NewReplacer(
		`\`, `\\`,
		"\n", `\n`,
		"\r", `\r`,
		"\t", `\t`,
	)
	return replacer.Replace(value)
}
