func TestExtractArcGISCollectionQuery(t *testing.T) {
	jrxml := `<?xml version="1.0" encoding="UTF-8"?>
<jasperReport name="Neighborhoods">
  <property name="acugis.datasource.provider" value="arcgis"/>
  <property name="acugis.datasource.connection" value="NeighborhoodsFS"/>
  <query language="collection"><![CDATA[SELECT "n"."name", "n"."division" FROM "layers"."neighborhoods" "n" WHERE $X{IN, "n"."division", p_div}]]></query>
</jasperReport>`
	info := reports.ExtractCollectionQueryInfo([]byte(jrxml))
	if !info.IsArcGISCollection() || !info.IsCollectionFill() {
		t.Fatalf("arcgis collection lang=%q provider=%q", info.Language, info.Provider)
	}
	if info.Connection != "NeighborhoodsFS" {
		t.Fatalf("connection=%q", info.Connection)
	}
	if info.IsCassandraCollection() || info.IsBigQueryCollection() || info.IsDuckDB() || info.IsGeoServerCollection() {
		t.Fatal("arcgis must not match cassandra, bigquery, duckdb, or geoserver")
	}
	if !strings.Contains(info.Query, `$X{IN, "n"."division", p_div}`) {
		t.Fatalf("query=%q", info.Query)
	}
}

