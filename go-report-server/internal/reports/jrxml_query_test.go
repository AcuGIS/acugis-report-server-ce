func TestCollectionFillProvidersStayDistinct(t *testing.T) {
	cases := []struct {
		name  string
		jrxml string
		cass  bool
		bq    bool
		arc   bool
		gs    bool
		csv   bool
		json  bool
		excel bool
		fill  bool
	}{
		{
			name:  "cassandra",
			jrxml: `<jasperReport><property name="acugis.datasource.provider" value="cassandra"/><query language="cassandra"><![CDATA[SELECT id FROM ks.t]]></query></jasperReport>`,
			cass:  true, fill: true,
		},
		{
			name:  "bigquery",
			jrxml: `<jasperReport><property name="acugis.datasource.provider" value="bigquery"/><query language="collection"><![CDATA[SELECT 1]]></query></jasperReport>`,
			bq:    true, fill: true,
		},
		{
			name:  "arcgis",
			jrxml: `<jasperReport><property name="acugis.datasource.provider" value="arcgis"/><query language="collection"><![CDATA[SELECT "a" FROM "layers"."t"]]></query></jasperReport>`,
			arc:   true, fill: true,
		},
		{
			name:  "geoserver",
			jrxml: `<jasperReport><property name="acugis.datasource.provider" value="geoserver"/><property name="acugis.datasource.connection" value="ProdGeoServer"/><query language="collection"><![CDATA[SELECT "name" FROM "transport"."roads"]]></query></jasperReport>`,
			gs:    true, fill: true,
		},
		{
			name:  "duckdb",
			jrxml: `<jasperReport><property name="acugis.datasource.provider" value="duckdb"/><query language="duckdb"><![CDATA[SELECT 1]]></query></jasperReport>`,
			fill:  false,
		},
		{
			name:  "csv",
			jrxml: `<jasperReport><property name="acugis.datasource.provider" value="csv"/><property name="acugis.datasource.resource" value="data/customers.csv"/><property name="acugis.datasource.delimiter" value="comma"/><query language="collection"><![CDATA[SELECT "customer" FROM "data"."customers"]]></query></jasperReport>`,
			csv:   true, fill: true,
		},
		{
			name:  "json",
			jrxml: `<jasperReport><property name="acugis.datasource.provider" value="json"/><property name="acugis.datasource.json.source" value="file"/><property name="acugis.datasource.resource" value="data/customers.json"/><property name="acugis.datasource.json.collection" value="customers"/><query language="collection"><![CDATA[SELECT "customer" FROM "data"."customers"]]></query></jasperReport>`,
			json:  true, fill: true,
		},
		{
			name:  "excel",
			jrxml: `<jasperReport><property name="acugis.datasource.provider" value="excel"/><property name="acugis.datasource.resource" value="data/sales.xlsx"/><property name="acugis.datasource.excel.sheet" value="Orders"/><query language="collection"><![CDATA[SELECT "Customer" FROM "data"."Orders"]]></query></jasperReport>`,
			excel: true, fill: true,
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			info := reports.ExtractCollectionQueryInfo([]byte(tc.jrxml))
			if info.IsCassandraCollection() != tc.cass || info.IsBigQueryCollection() != tc.bq || info.IsArcGISCollection() != tc.arc || info.IsGeoServerCollection() != tc.gs || info.IsCSVCollection() != tc.csv || info.IsJSONCollection() != tc.json || info.IsExcelCollection() != tc.excel || info.IsCollectionFill() != tc.fill {
				t.Fatalf("cass=%v bq=%v arc=%v gs=%v csv=%v json=%v excel=%v fill=%v", info.IsCassandraCollection(), info.IsBigQueryCollection(), info.IsArcGISCollection(), info.IsGeoServerCollection(), info.IsCSVCollection(), info.IsJSONCollection(), info.IsExcelCollection(), info.IsCollectionFill())
			}
			if tc.csv && (info.Resource != "data/customers.csv" || info.Delimiter != "comma") {
				t.Fatalf("resource=%q delimiter=%q", info.Resource, info.Delimiter)
			}
			if tc.json && (info.Resource != "data/customers.json" || info.JSONSource != "file" || info.JSONCollection != "customers" || info.JSONURLMode()) {
				t.Fatalf("json info %+v", info)
			}
			if tc.excel && (info.Resource != "data/sales.xlsx" || info.ExcelSheet != "Orders") {
				t.Fatalf("excel info %+v", info)
			}
			if tc.gs && info.Connection != "ProdGeoServer" {
				t.Fatalf("connection=%q", info.Connection)
			}
		})
	}
}

func TestExtractDuckDBCollectionQuery(t *testing.T) {
	jrxml := `<?xml version="1.0"?>
<jasperReport>
  <property name="acugis.datasource.provider" value="duckdb"/>
  <property name="acugis.datasource.connection.method" value="files"/>
  <property name="acugis.datasource.files" value="yellow_tripdata_2024_01"/>
  <query language="duckdb"><![CDATA[SELECT VendorID, total_amount
FROM read_parquet('https://acugis.cloud/yellow_tripdata_2024-01.parquet')
WHERE VendorID = 2
LIMIT 100]]></query>
</jasperReport>`
	info := reports.ExtractCollectionQueryInfo([]byte(jrxml))
	if !info.IsDuckDB() {
		t.Fatalf("expected duckdb, lang=%q provider=%q", info.Language, info.Provider)
	}
	if !strings.Contains(info.Query, "read_parquet") {
		t.Fatalf("query must preserve read_parquet: %q", info.Query)
	}
	if info.IsBigQueryCollection() || info.IsCassandraCollection() {
		t.Fatal("must not be bigquery/cassandra")
	}
	if info.IsCollectionFill() {
		t.Fatal("DuckDB must not use Go collection fill")
	}
}
