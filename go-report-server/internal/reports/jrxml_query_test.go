func TestExtractCollectionQueryFromJRXML(t *testing.T) {
	jrxml := `<?xml version="1.0"?>
<jasperReport>
  <property name="acugis.datasource.provider" value="cassandra"/>
  <queryString language="cassandra"><![CDATA[SELECT customer_id, sales FROM ks.customers WHERE state = $P{p_state}]]></queryString>
  <field name="sales" class="java.math.BigDecimal"/>
</jasperReport>`
	info := reports.ExtractCollectionQueryInfo([]byte(jrxml))
	want := "SELECT customer_id, sales FROM ks.customers WHERE state = $P{p_state}"
	if info.Query != want {
		t.Fatalf("got %q want %q", info.Query, want)
	}
	if !info.IsCassandraCollection() {
		t.Fatalf("expected cassandra collection, lang=%q provider=%q", info.Language, info.Provider)
	}
}

func TestExtractCollectionQueryFromJR7QueryElement(t *testing.T) {
	// AcuGIS Report Designer (JasperReports 7) emits <query>, not Digester <queryString>.
	jrxml := `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by AcuGIS Report Designer -->
<jasperReport name="Cassandra_Customers" language="java" pageWidth="612" pageHeight="792" columnWidth="572" leftMargin="20" rightMargin="20" topMargin="20" bottomMargin="20">
  <property name="acugis.jrxml.target" value="7.0.1"/>
  <property name="acugis.datasource.provider" value="cassandra"/>
  <query language="cassandra"><![CDATA[SELECT active, city, created_at, customer_name, sales, state
FROM default_keyspace.customers]]></query>
  <field name="sales" class="java.math.BigDecimal"/>
</jasperReport>`
	info := reports.ExtractCollectionQueryInfo([]byte(jrxml))
	want := "SELECT active, city, created_at, customer_name, sales, state\nFROM default_keyspace.customers"
	if info.Query != want {
		t.Fatalf("got %q want %q", info.Query, want)
	}
	if info.Language != "cassandra" {
		t.Fatalf("language=%q", info.Language)
	}
	if !info.IsCassandraCollection() {
		t.Fatalf("expected cassandra collection, lang=%q provider=%q", info.Language, info.Provider)
	}
}

func TestExtractCollectionQueryIgnoresSQLLanguage(t *testing.T) {
	jrxml := `<?xml version="1.0"?>
<jasperReport>
  <queryString language="SQL"><![CDATA[SELECT 1]]></queryString>
</jasperReport>`
	info := reports.ExtractCollectionQueryInfo([]byte(jrxml))
	// SQL is last-resort fallback when no cassandra/collection language is present.
	if info.Query != "SELECT 1" {
		t.Fatalf("got %q", info.Query)
	}
	if info.IsCassandraCollection() {
		t.Fatal("SQL query should not be treated as cassandra collection")
	}
}

